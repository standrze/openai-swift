#!/usr/bin/env python3
"""Generate named Swift REST descriptors from independently extracted upstream route facts."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import sys


def rendered_files(root):
    reference = json.loads((root / "Documentation/Reference/openai-go-endpoints.json").read_text())
    groups = defaultdict(list)
    for operation in reference["operations"]:
        groups[operation["upstreamSymbol"].split(".")[1]].append(operation)
    outputs = {}
    for group, operations in sorted(groups.items()):
        lines = [
            "// Generated by scripts/generate-endpoints.py from pinned upstream REST route facts.",
            "// Revision: " + reference["revision"],
            "import Foundation", "", "extension RESTEndpoint {",
        ]
        for operation in operations:
            lines.extend([
                "    /// " + operation["method"] + " /" + operation["path"],
                "    public static let " + operation["name"] + " = Self(",
                "        name: " + json.dumps(operation["name"]) + ",",
                "        method: ." + operation["method"].lower() + ",",
                "        pathTemplate: " + json.dumps(operation["path"]) + ",",
                "        upstreamSymbol: " + json.dumps(operation["upstreamSymbol"]),
                "    )", "",
            ])
        lines[-1] = "}"
        outputs[root / ("Sources/OpenAI/Endpoints/RESTEndpoint+" + group + ".swift")] = "\n".join(lines) + "\n"
    lines = [
        "// Generated by scripts/generate-endpoints.py from pinned upstream REST route facts.",
        "import Foundation", "", "extension RESTEndpoint {",
        "    /// The exact upstream revision used by this operation catalog.",
        "    public static let upstreamRevision = " + json.dumps(reference["revision"]),
        "", "    /// Every named REST operation in the pinned root and linked API references.",
        "    public static let all: [RESTEndpoint] = [",
    ]
    lines.extend("        ." + operation["name"] + "," for operation in reference["operations"])
    lines.extend(["    ]", "}"])
    outputs[root / "Sources/OpenAI/Endpoints/RESTEndpoint+Catalog.swift"] = "\n".join(lines) + "\n"
    outputs[root / "Tests/OpenAITests/Fixtures/EndpointReference.json"] = json.dumps(reference, indent=2) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    mismatches = []
    for path, expected in rendered_files(root).items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                mismatches.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if mismatches:
        raise SystemExit("Endpoint generation differs: " + ", ".join(mismatches))
    print("Endpoint catalog " + ("checked" if args.check else "generated"))


if __name__ == "__main__":
    main()
